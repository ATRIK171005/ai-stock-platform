// Generates 90 days of realistic daily OHLCV candles
export function generateSampleCandles(basePrice: number, days = 90): OHLCVCandle[] {
  const candles: OHLCVCandle[] = [];
  let current = basePrice * 0.88;
  const startDate = new Date();
  startDate.setDate(startDate.getDate() - days);

  for (let i = 0; i < days; i++) {
    const d = new Date(startDate);
    d.setDate(d.getDate() + i);

    // Skip weekends
    if (d.getDay() === 0 || d.getDay() === 6) continue;

    const dateStr = d.toISOString().split('T')[0];
    const dailyVol = 0.015;
    const changePct = (Math.random() - 0.48) * dailyVol;
    const open = Math.round(current * (1 + (Math.random() - 0.5) * 0.006) * 100) / 100;
    const close = Math.round(current * (1 + changePct) * 100) / 100;
    const high = Math.round(Math.max(open, close) * (1 + Math.random() * 0.01) * 100) / 100;
    const low = Math.round(Math.min(open, close) * (1 - Math.random() * 0.01) * 100) / 100;
    const volume = Math.floor(2000000 + Math.random() * 7000000);

    candles.push({
      time: dateStr,
      open,
      high,
      low,
      close,
      volume,
    });
    current = close;
  }
  return candles;
}

